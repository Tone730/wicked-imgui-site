#!/usr/bin/env node
// Regenerate js/checkout-links.js from environment variables. No dependencies.
// Empty values clear a link and keep the dashboard's honest "not configured" state.
//   CHECKOUT_URL_MONTHLY=https://... CHECKOUT_URL_YEARLY=https://... \
//   CHECKOUT_PORTAL_URL=https://... PAYHIP_URL=https://... node tools/set-checkout-urls.js
// It also reads ../.env (copy .env.example to .env and fill it), so the links can be
// regenerated without putting URLs or secrets in shell history.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

(function loadEnv() {
  const file = path.resolve(__dirname, '..', '.env');
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch { return; }
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const at = trimmed.indexOf('=');
    if (at < 0) continue;
    const key = trimmed.slice(0, at).trim();
    if (!/^[A-Z0-9_]+$/.test(key) || Object.prototype.hasOwnProperty.call(process.env, key)) continue;
    let value = trimmed.slice(at + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    process.env[key] = value;
  }
})();

const MAP = {
  monthly: 'CHECKOUT_URL_MONTHLY',
  yearly: 'CHECKOUT_URL_YEARLY',
  portal: 'CHECKOUT_PORTAL_URL',
  payhip: 'PAYHIP_URL',
  gumroad: 'GUMROAD_URL',
  kofi: 'KOFI_URL',
  sponsors: 'SPONSORS_URL',
  paypal: 'PAYPAL_URL',
};
const values = {};
for (const [key, env] of Object.entries(MAP)) {
  const raw = String(process.env[env] || '').trim();
  if (raw && !/^https:\/\//i.test(raw)) throw new Error(`${env} must be an https:// URL (or empty to clear it).`);
  values[key] = raw;
}
const q = (s) => JSON.stringify(s);
const source = `// Generated by tools/set-checkout-urls.js — do not edit by hand.
// Regenerate: node tools/set-checkout-urls.js
export const CHECKOUT_LINKS = Object.freeze({
  monthly: ${q(values.monthly)},
  yearly: ${q(values.yearly)},
  portal: ${q(values.portal)},
  alternatives: Object.freeze({
    payhip: ${q(values.payhip)},
    gumroad: ${q(values.gumroad)},
    kofi: ${q(values.kofi)},
    sponsors: ${q(values.sponsors)},
    paypal: ${q(values.paypal)},
  }),
});
`;
const target = path.resolve(__dirname, '..', 'js', 'checkout-links.js');
fs.writeFileSync(target, source);
console.log(`Updated ${target}`);
console.log(Object.entries(values).map(([k, v]) => `  ${k}: ${v || '(cleared)'}`).join('\n'));
